def nombre_total_livre(liste_livres):
    somme = 0
    for livre in liste_livres:
        somme += 1
    print(f"le nombre TOTAL de livres est : {somme}\n")

def nombre_total_utilisateur(liste_utilisateurs):
    somme = 0
    for utilisateur in liste_utilisateurs:
        somme += 1
    print(f"le nombre TOTAL d'utilisateurs est : {somme}\n")


